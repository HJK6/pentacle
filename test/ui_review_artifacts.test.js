test('saved History reload fetches the retained manifest before displaying revision content', async () => {
  const dom = new JSDOM('<main></main>', { url: 'https://app.example.test/designs/' }), old = 'b'.repeat(64);
  const data = structuredClone(catalog); data.projects[0].revisions = [{ revision_id: old, source_revision: 'old-A', complete: true }];
  data.projects[0].manifest.views[0].title = 'Current B';
  dom.window.sessionStorage.setItem('design-gallery.selection', JSON.stringify({ project: 'example', revision: old, item: 'home', kind: 'views', mode: 'screens' }));
  let resolve, requested; const pending = new Promise(done => { resolve = done; });
  const refs = library.mountGallery(dom.window.document.querySelector('main'), { fetch: url => { requested = url; return pending; } }); library.updateGallery(refs, data);
  assert.equal(refs.root.querySelector('h1').textContent.includes('Current B'), false, 'must not show current while the older History choice is pending');
  const retained = structuredClone(data.projects[0].manifest); retained.revision_id = old; retained.project_id = 'example'; retained.views[0].title = 'Retained A'; retained.views[0].prototype = false;
  resolve({ ok: true, json: async () => retained }); await new Promise(done => setImmediate(done));
  assert.equal(requested, '/api/designs/example/' + old); assert.equal(refs.root.querySelector('h1').textContent, 'Retained A'); assert.ok(refs.root.querySelector('img').src.includes('/' + old + '/')); assert.equal(refs.root.querySelector('[aria-label="History"]').value, old);
  library.unmountGallery(refs); dom.window.close();
});
test('gallery defaults each opened view by capability, including stale saved Screens selections', async () => {
  const dom = new JSDOM('<main></main>', { url: 'https://app.example.test/designs/' });
  const data = structuredClone(catalog);
  data.projects[0].manifest.views.push({ ...item, id: 'still', title: 'Still', prototype: false });
  dom.window.sessionStorage.setItem('design-gallery.selection', JSON.stringify({ project: 'example', item: 'home', kind: 'views', mode: 'screens' }));
  const options = { fetch: async () => ({ ok: true, json: async () => ({ document: '<h1>Clickable</h1>' }) }) };
  let refs = library.mountGallery(dom.window.document.querySelector('main'), options);
  library.updateGallery(refs, data);
  await new Promise(resolve => setImmediate(resolve));
  assert.ok(refs.root.querySelector('iframe'), 'a saved Screens default must not hide the prototype on reopen');
  const screenButton = () => [...refs.root.querySelectorAll('.dg-modes button')].find(b => b.textContent === 'Screens');
  screenButton().click();
  assert.ok(refs.root.querySelector('img'), 'Screens remains available by explicit choice');
  const refreshed = structuredClone(data); refreshed.projects[0].sync = 'pending';
  library.updateGallery(refs, refreshed);
  assert.equal(refs.state.mode, 'screens', 'catalog polling preserves the explicit mode on the same view');
  const search = refs.root.querySelector('input'); search.value = 'Home'; search.dispatchEvent(new dom.window.Event('input'));
  assert.equal(refs.state.mode, 'screens', 'search does not reset the explicit mode');
  search.value = ''; search.dispatchEvent(new dom.window.Event('input'));
  refs.root.querySelector('[data-item="still"]').click();
  assert.equal(refs.state.mode, 'screens');
  assert.ok(refs.root.querySelector('img'));
  refs.root.querySelector('[data-item="home"]').click();
  await new Promise(resolve => setImmediate(resolve));
  assert.ok(refs.root.querySelector('iframe'), 'returning to the clickable view restores its prototype default');
  screenButton().click();
  library.unmountGallery(refs);
  refs = library.mountGallery(dom.window.document.querySelector('main'), options);
  library.updateGallery(refs, data);
  await new Promise(resolve => setImmediate(resolve));
  assert.ok(refs.root.querySelector('iframe'), 'remount opens the selected clickable view interactively');
  refs.root.querySelector('[data-item="still"]').click();
  library.unmountGallery(refs);
  refs = library.mountGallery(dom.window.document.querySelector('main'), options);
  library.updateGallery(refs, data);
  assert.ok(refs.root.querySelector('img'), 'a saved screenshot-only view reopens as Screens');
  library.unmountGallery(refs); dom.window.close();
});
